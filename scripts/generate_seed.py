#!/usr/bin/env python3
"""Generate supabase/seed.sql from data/words.txt (fails on duplicate words)."""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
rows, seen = [], set()

for line in (root / "data" / "words.txt").read_text(encoding="utf-8").splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    slug, diff, words = line.split("|")
    for w in (x.strip() for x in words.split(",")):
        if not w:
            continue
        if w in seen:
            sys.exit(f"duplicate word: {w}")
        seen.add(w)
        rows.append((w, slug, int(diff)))


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


values = ",\n".join(f"  ({q(w)}, {q(s)}, {d})" for w, s, d in rows)
sql = (
    "-- Generated by scripts/generate_seed.py — edit data/words.txt and re-run.\n"
    f"-- {len(rows)} Hebrew words\n"
    "insert into public.words (word, category_id, difficulty)\n"
    "select v.word, c.id, v.difficulty\n"
    "from (values\n"
    f"{values}\n"
    ") as v(word, slug, difficulty)\n"
    "join public.categories c on c.slug = v.slug\n"
    "on conflict (word, category_id) do nothing;\n"
)
(root / "supabase" / "seed.sql").write_text(sql, encoding="utf-8")
print(f"wrote supabase/seed.sql with {len(rows)} words")
